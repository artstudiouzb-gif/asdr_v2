<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Ритм ленты новостей: каждая пятая карточка выводится широкой — с анонсом и
 * фотографией сбоку.
 *
 * Зачем: страница из двенадцати одинаковых карточек читается как таблица, глазу
 * не за что зацепиться. Широкая карточка разбивает сетку и заодно показывает
 * анонс, который в компактной карточке не помещается.
 *
 * Почему именно каждая пятая. Широкая карточка занимает **две ячейки** сетки,
 * значит группа «4 компактные + 1 широкая» — это ровно шесть ячеек. Шесть
 * делится и на 4, и на 3, и на 2 колонки, поэтому ряды остаются полными на
 * любой ширине экрана: дырок посреди ленты не появляется. Отсюда и размер
 * страницы — 10 карточек, то есть 12 ячеек, две полные группы.
 *
 * Первая новость на первой странице в ленту не входит: она показывается
 * отдельной крупной карточкой над сеткой.
 */
final class NewsFeedRhythm
{
    /** Каждая GROUP-я карточка сетки — широкая. */
    public const GROUP = 5;

    /** Ячеек сетки в одной группе: (GROUP - 1) компактных плюс широкая на две. */
    public const CELLS_PER_GROUP = self::GROUP + 1;

    /** Карточек в сетке одной страницы: две полные группы. */
    public const PAGE_SIZE = self::GROUP * 2;

    /**
     * Широкая ли карточка сетки. Индекс — с нуля, в пределах страницы.
     *
     * Неполная группа в хвосте широкой карточки не получает: она пришлась бы
     * на незаполненный ряд.
     */
    public static function isWide(int $index): bool
    {
        return $index >= 0 && ($index + 1) % self::GROUP === 0;
    }
}
