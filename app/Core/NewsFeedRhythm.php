<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Ритм ленты новостей: цикл «крупная плюс две компактные» → ряд из четырёх
 * компактных → «две компактные плюс крупная».
 *
 * Зачем: страница из одинаковых карточек читается как таблица, глазу не за что
 * зацепиться. Крупная карточка разбивает сетку и показывает анонс, который в
 * компактную не помещается.
 *
 * Почему цикл именно такой. Крупная карточка занимает **две ячейки** сетки,
 * поэтому «крупная + две компактные» — ровно четыре ячейки, то есть один
 * полный ряд при четырёх колонках. Между двумя такими рядами стоит ряд из
 * четырёх компактных карточек, а в третьем ряду крупная уходит вправо: лента
 * идёт зигзагом, а не повторяет одну и ту же строку сверху вниз. Итого цикл —
 * десять карточек и двенадцать ячеек, то есть три полных ряда при четырёх
 * колонках и шесть при двух.
 *
 * А вот на три колонки цикл не раскладывается: крупная карточка рано или
 * поздно упирается в последнюю колонку, где ей не хватает места, сетка
 * переносит её на следующий ряд и оставляет дыру. Поэтому на трёх колонках
 * ритм выключается в CSS — все карточки компактные (см. gov-theme.css).
 *
 * Первая новость входит в ленту наравне с остальными: отдельной крупной
 * карточки над сеткой нет, лента начинается с крупной карточки цикла.
 */
final class NewsFeedRhythm
{
    /** Карточек в цикле: две крупные и восемь компактных. */
    public const CYCLE = 10;

    /** Ячеек сетки в цикле: каждая крупная занимает две. */
    public const CELLS_PER_CYCLE = 12;

    /**
     * Места крупных карточек в цикле (индекс с нуля).
     *
     * Ноль — начало первого ряда (крупная слева), девять — конец третьего
     * (крупная справа, после двух компактных). Между ними ряд из четырёх
     * компактных карточек.
     */
    public const WIDE_POSITIONS = [0, 9];

    /** Карточек на странице: два полных цикла. */
    public const PAGE_SIZE = 20;

    /**
     * Крупная ли карточка. Индекс — с нуля, в пределах страницы.
     */
    public static function isWide(int $index): bool
    {
        return $index >= 0 && in_array($index % self::CYCLE, self::WIDE_POSITIONS, true);
    }
}
