<?php

declare(strict_types=1);

namespace App\Core;

/**
 * Ритм ленты новостей: группа «одна крупная карточка плюс две компактные».
 *
 * Зачем: страница из одинаковых карточек читается как таблица, глазу не за что
 * зацепиться. Крупная карточка разбивает сетку и показывает анонс, который в
 * компактную не помещается.
 *
 * Почему группа именно такая. Крупная карточка занимает **две ячейки** сетки,
 * значит группа «1 крупная + 2 компактные» — это ровно четыре ячейки, то есть
 * при четырёх колонках один полный ряд: крупная слева, две компактные справа.
 * При двух колонках группа занимает два ряда — тоже без дыр.
 *
 * А вот на три колонки четыре ячейки не делятся, и крупная карточка рано или
 * поздно упирается в последнюю колонку, где ей не хватает места: сетка
 * переносит её на следующий ряд и оставляет дыру. Поэтому на трёх колонках
 * ритм выключается в CSS — все карточки компактные (см. gov-theme.css).
 *
 * Первая новость входит в ленту наравне с остальными: отдельной крупной
 * карточки над сеткой больше нет, лента начинается с крупной карточки группы.
 */
final class NewsFeedRhythm
{
    /** Карточек в группе: одна крупная и две компактные. */
    public const GROUP = 3;

    /** Ячеек сетки в одной группе: крупная занимает две плюс две компактные. */
    public const CELLS_PER_GROUP = 4;

    /** Карточек на странице: четыре полные группы. */
    public const PAGE_SIZE = 12;

    /**
     * Крупная ли карточка. Индекс — с нуля, в пределах страницы.
     *
     * Крупной становится первая карточка каждой группы: лента открывается ею,
     * и дальше ритм повторяется без исключений для первой страницы.
     */
    public static function isWide(int $index): bool
    {
        return $index >= 0 && $index % self::GROUP === 0;
    }
}
