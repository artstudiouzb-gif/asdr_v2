-- Удаление таблицы WebAuthn/Passkey.
--
-- Реализация была заглушкой: вход подтверждался одним credential_id без
-- проверки подписи, challenge и счётчика, то есть публичным идентификатором.
-- Маршруты /admin/passkey/* никогда не регистрировались, поэтому записей в
-- таблице нет. Код удалён целиком (см. SECURITY.md); настоящий WebAuthn при
-- необходимости заводится заново вместе со своей схемой.
--
-- Так и вышло: 2026_09_26_user_passkeys.sql заводит таблицу заново под
-- настоящий WebAuthn. Поэтому эта миграция больше не post-schema: schema.sql
-- уже описывает итог (новую таблицу), и на свежей установке сносить её нельзя.
DROP TABLE IF EXISTS `user_passkeys`;
